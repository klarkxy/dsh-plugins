// Build-time, read-only vendor CSS collection. Runtime code never reads
// node_modules and no third-party selector escapes the plugin root.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import postcss from 'postcss'

const require = createRequire(import.meta.url)
const scoped = path => {
  const root = postcss.parse(readFileSync(require.resolve(path), 'utf8'))
  root.walkRules(rule => {
    if (rule.parent?.type === 'atrule' && /keyframes/i.test(rule.parent.name)) return
    rule.selectors = rule.selectors.map(selector => /^(?:html|body|:root)(?![\w-])/.test(selector.trim())
      ? selector.replace(/^(?:html|body|:root)/, '.dvui-root')
      : `.dvui-root ${selector}`)
  })
  return root.toString()
}
const css = [scoped('@xyflow/react/dist/style.css'), scoped('maplibre-gl/dist/maplibre-gl.css')].join('\n')
const out = new URL('../src/vendor-css.generated.ts', import.meta.url)
writeFileSync(out, `// Generated by scripts/vendor-css.mjs; do not edit by hand.\nexport const vendorCss = ${JSON.stringify(css)}\n`, 'utf8')
console.log(`Scoped vendor CSS: ${css.length} characters`)
