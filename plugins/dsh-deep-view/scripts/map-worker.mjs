// Embed MapLibre's official browser worker as data in the single client module.
// DSH creates no extra module-table entries and the model never supplies code.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const source = resolve(here, '../../../node_modules/maplibre-gl/dist/maplibre-gl-worker.mjs')
const target = resolve(here, '../src/map-worker.generated.ts')
const worker = readFileSync(source, 'utf8')
writeFileSync(target, `// Generated by scripts/map-worker.mjs from maplibre-gl's pinned worker.\nexport const mapWorkerSource = ${JSON.stringify(worker)}\n`)
