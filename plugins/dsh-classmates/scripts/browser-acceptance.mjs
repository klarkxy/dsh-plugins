import { openClassmatesSettings, scrollPluginSettingsToTop } from './plugin-settings-navigation.mjs';
import { chromium, expect } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
const url = process.env.DSH_ACCEPTANCE_URL;
if (!url) throw Error('Set DSH_ACCEPTANCE_URL to the local test host URL');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const errors = [];
const checks = [];
const roleName = `UI Acceptance ${Date.now()}`;
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  async function settings(page) {
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(url);
    await page.getByRole('button', { name: '设置', exact: true }).waitFor();
    const onboarding = page.getByRole('button', { name: '继续', exact: true });
    if (await onboarding.isVisible()) await onboarding.click();
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await expect(page.getByRole('button', { name: '通用设置', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Classmates', exact: true })).toHaveCount(0);
    await page.keyboard.press('Escape');
    await openClassmatesSettings(page);
  }
  const page = await context.newPage();
  await settings(page);
  const initialRoleCount = await page.locator('.classmates-item').count();
  await page.getByRole('button', { name: '新建角色', exact: true }).click();
  await page.getByLabel('名称', { exact: true }).fill(roleName);
  await page.getByLabel('职责说明', { exact: true }).fill('Check the settings workflow.');
  await page.getByLabel('工作指令', { exact: true }).fill('Return a short answer.');
  const model = page.getByLabel('模型', { exact: true });
  const mini = await model.locator('option').filter({ hasText: process.env.DSH_ACCEPTANCE_MODEL_A || 'ocg/minimax-m3' }).getAttribute('value');
  const mimo = await model.locator('option').filter({ hasText: process.env.DSH_ACCEPTANCE_MODEL_B || 'ocg/mimo-v2.6-flash' }).getAttribute('value');
  await model.selectOption(mini);
  await page.getByLabel('思考强度', { exact: true }).selectOption('high');
  await model.selectOption(mimo);
  await expect(page.getByLabel('思考强度', { exact: true })).toHaveValue('high');
  await page.getByLabel('思考强度', { exact: true }).selectOption('');
  checks.push('model switch preserves effort; explicit reset follows chat');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.locator('.classmates-notice')).toContainText('已保存');
  await expect(page.getByRole('button', { name: '保存', exact: true })).toBeEnabled();
  await expect(page.locator('.classmates-item').filter({ hasText: roleName })).toHaveCount(1);
  await expect(page.getByRole('switch', { name: '启用角色 ' + roleName, exact: true })).not.toBeChecked();
  await page.getByLabel('职责说明', { exact: true }).fill('Draft kept during toggle');
  await page.getByRole('switch', { name: '启用角色 ' + roleName, exact: true }).click();
  await expect(page.getByRole('switch', { name: '启用角色 ' + roleName, exact: true })).toBeChecked();
  await expect(page.getByLabel('职责说明', { exact: true })).toHaveValue('Draft kept during toggle');
  await expect(page.locator('.classmates-dirty')).toBeVisible();
  const observer = await context.newPage();
  await settings(observer);
  await observer.locator('.classmates-item').filter({ hasText: roleName }).click();
  await expect(observer.getByRole('switch', { name: '启用角色 ' + roleName, exact: true })).toBeChecked();
  await expect(observer.getByLabel('职责说明', { exact: true })).toHaveValue('Check the settings workflow.');
  await observer.close();
  // An unrelated row's toggle must also leave this editor's draft alone.
  const otherSwitch = page.locator('.classmates-row').filter({ hasNotText: roleName }).getByRole('switch').first();
  const originalOtherState = await otherSwitch.isChecked();
  await otherSwitch.click();
  await expect(otherSwitch).toHaveAttribute('aria-checked', String(!originalOtherState));
  await expect(page.getByLabel('职责说明', { exact: true })).toHaveValue('Draft kept during toggle');
  await otherSwitch.click();
  await expect(otherSwitch).toHaveAttribute('aria-checked', String(originalOtherState));
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.locator('.classmates-notice')).toContainText('已保存');
  checks.push('list switches persist immediately without saving or losing same-role and other-role drafts');
  await page.reload();
  await openClassmatesSettings(page);
  await page.locator('.classmates-item').filter({ hasText: roleName }).click();
  await expect(page.getByRole('switch', { name: '启用角色 ' + roleName, exact: true })).toBeChecked();
  checks.push('plugin entry, no general-settings entry, create, native switch, save and reload persistence');

  const second = await context.newPage();
  await settings(second);
  await second.locator('.classmates-item').filter({ hasText: roleName }).click();
  await page.getByLabel('名称', { exact: true }).fill(`${roleName} updated`);
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.locator('.classmates-notice')).toContainText('已保存');
  await second.getByLabel('职责说明', { exact: true }).fill('Unsaved local change');
  await second.getByRole('switch', { name: '启用角色 ' + roleName, exact: true }).click();
  await expect(second.locator('.classmates-list-error')).toContainText('未能确认');
  await expect(second.getByRole('switch', { name: '启用角色 ' + roleName, exact: true })).toBeChecked();
  await second.getByRole('button', { name: '刷新角色列表', exact: true }).click();
  await expect(second.locator('.classmates-list-error')).toHaveCount(0);
  await expect(second.getByLabel('职责说明', { exact: true })).toHaveValue('Unsaved local change');
  await second.getByRole('switch', { name: '启用角色 ' + roleName + ' updated', exact: true }).click();
  await expect(second.getByRole('switch', { name: '启用角色 ' + roleName + ' updated', exact: true })).not.toBeChecked();
  checks.push('stale toggle refused; refresh and retry preserve text draft and conflict protection');
  await second.getByRole('button', { name: '保存', exact: true }).click();
  await expect(second.locator('.classmates-alert')).toContainText('保存失败');
  await expect(second.getByLabel('职责说明', { exact: true })).toHaveValue('Unsaved local change');
  await second.getByRole('button', { name: '加载最新版本', exact: true }).click();
  await expect(second.locator('.classmates-remote')).toContainText(`${roleName} updated`);
  await expect(second.getByLabel('职责说明', { exact: true })).toHaveValue('Unsaved local change');
  await second.getByRole('button', { name: '改用最新版本', exact: true }).click();
  await expect(second.getByLabel('名称', { exact: true })).toHaveValue(`${roleName} updated`);
  checks.push('conflict preserves draft and shows remote changes');

  await second.getByRole('button', { name: '收起侧边栏', exact: true }).click();
  await second.setViewportSize({ width: 320, height: 844 });
  await expect(second.locator('.classmates-back')).toBeVisible();
  const overflow = await second.locator('.classmates').evaluate(element => ({ width: element.clientWidth, scrollWidth: element.scrollWidth }));
  if (overflow.scrollWidth > overflow.width + 1) throw Error(`Mobile overflow ${JSON.stringify(overflow)}`);
  const documentOverflow = await second.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  if (documentOverflow) throw Error('The mobile document overflows horizontally');
  const mobileSave = second.getByRole('button', { name: '保存', exact: true });
  await mobileSave.scrollIntoViewIfNeeded();
  const bounds = await mobileSave.boundingBox();
  if (!bounds || bounds.x < 0 || bounds.x + bounds.width > 320) throw Error('Mobile save action is clipped');
  await second.screenshot({ path: '.test-output/classmates-mobile-actions.png', fullPage: true });
  await scrollPluginSettingsToTop(second);
  await second.screenshot({ path: '.test-output/classmates-mobile.png', fullPage: true });
  checks.push('320px mobile layout');
  await second.setViewportSize({ width: 1440, height: 1000 });
  await scrollPluginSettingsToTop(second);
  await second.screenshot({ path: '.test-output/classmates-editor.png', fullPage: true });
  await second.getByRole('button', { name: '设置', exact: true }).click();
  await second.getByRole('button', { name: '通用设置', exact: true }).click();
  await second.getByRole('button', { name: '深色', exact: true }).click();
  await second.keyboard.press('Escape');
  await second.locator('.classmates-item').filter({ hasText: roleName }).click();
  await scrollPluginSettingsToTop(second);
  const buttonColors = await second.getByRole('button', { name: '保存', exact: true }).evaluate(element => {
    const style = getComputedStyle(element); return { color: style.color, background: style.backgroundColor };
  });
  if (buttonColors.color === buttonColors.background) throw Error('Dark-theme save button has no text contrast');
  await second.screenshot({ path: '.test-output/classmates-dark.png', fullPage: true });
  checks.push('native dark theme');

  second.once('dialog', dialog => dialog.accept());
  await second.getByRole('button', { name: '删除角色', exact: true }).click();
  await expect(second.locator('.classmates-notice')).toContainText('已删除');
  await expect(second.getByRole('button', { name: '新建角色', exact: true })).toBeEnabled();
  checks.push('delete and post-delete interaction');
  await second.getByRole('switch', { name: /^启用组件 (?:队友角色|@klarkxy\/dsh-classmates)$/ }).click();
  await expect(second.locator('.classmates')).toHaveCount(0);
  await expect(second.getByRole('switch', { name: /^启用组件 (?:队友角色|@klarkxy\/dsh-classmates)$/ })).not.toBeChecked();
  await expect(second.getByRole('switch', { name: /^启用组件 (?:队友角色|@klarkxy\/dsh-classmates)$/ })).toBeEnabled();
  await second.getByRole('switch', { name: /^启用组件 (?:队友角色|@klarkxy\/dsh-classmates)$/ }).click();
  await expect(second.getByRole('switch', { name: /^启用组件 (?:队友角色|@klarkxy\/dsh-classmates)$/ })).toBeChecked();
  await expect(second.locator('.classmates')).toHaveCount(1);
  await expect(second.locator('.classmates-item')).toHaveCount(initialRoleCount);
  checks.push('component disable disposes settings; re-enable mounts once and preserves original roles');
  const availableRole = second.locator('.classmates-row').getByRole('switch').first();
  if (!await availableRole.isChecked()) { await availableRole.click(); await expect(availableRole).toBeChecked(); }
  await expect(second.getByRole('button', { name: '打开角色配置助手', exact: true })).toHaveCount(0);
  await second.getByRole('button', { name: '开始任务', exact: true }).click();
  await expect(second.locator('.classmates')).toHaveCount(0);
  await expect(second.getByRole('textbox').last()).toBeEditable();
  checks.push('retired manager entry absent; start-task navigation leaves Plugins correctly');
  if (errors.length) throw Error(errors.join('\n'));
  await writeFile('.test-output/browser-acceptance.json', JSON.stringify({ checks, pageErrors: errors }, null, 2));
  console.log(JSON.stringify({ checks, pageErrors: errors }));
} finally { await browser.close(); }
