export type PageTranslate = (key: PageKey, params?: Record<string, unknown>) => string;

/** True when a host locale id names Chinese (zh, zh-CN, zh-Hans…). */
export function isChineseLocale(locale: string | undefined): boolean {
  return typeof locale === 'string' && locale.toLowerCase().startsWith('zh');
}

/** Local lookup with the host's `{name}` placeholder syntax. */
export function createPageTranslator(locale: string | undefined): PageTranslate {
  const dict: Record<PageKey, string> = isChineseLocale(locale) ? classmatesPageZh : classmatesPageEn;
  return (key, params) => {
    const template = dict[key] ?? classmatesPageEn[key] ?? key;
    if (!params) return template;
    return template.replace(/\{(\w+)\}/gu, (match, name: string) =>
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match);
  };
}
