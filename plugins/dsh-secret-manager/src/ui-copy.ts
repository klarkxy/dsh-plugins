export type UiTranslate = (key: UiKey, params?: Record<string, unknown>) => string

/** Fill `{name}` placeholders the way the host `t` seat does. */
export function fill(template: string, params?: Record<string, unknown>): string {
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params?.[name] ?? `{${name}}`))
}

/** One stable translator per locale for surfaces without the framework `t` seat. */
export function translator(locale: 'zh' | 'en'): UiTranslate {
  const table: Record<UiKey, string> = locale === 'en' ? uiEn : uiZh
  return (key, params) => fill(table[key] ?? key, params)
}
